//! The app's words in other languages (docs/design/language.md): the built-in
//! language files, and `zz`, the made-up language that marks every text in
//! the table, so a test can count what is not through `t()` yet.

use std::collections::{BTreeMap, BTreeSet};

use serde::Serialize;

/// A built-in language: (code, file text). The file is
/// `{ "name": "Nederlands", "texts": { "English text": "…" } }`. Add a line
/// here with the file in `data/lang/`; English has no file.
const LANGUAGES: &[(&str, &str)] = &[];

/// Every text the UI wraps or writes in markup (generated by `tools/lang-table.py`).
const KEYS: &str = include_str!("../data/lang/keys.json");

/// The words of Rust's tables: settings, mask fields, size presets (written by
/// a test: `AMB_UPDATE_DOCS=1 cargo test -p amb-gui lang`).
const BUILT_IN: &str = include_str!("../data/lang/built-in.json");

/// The code of the test language.
const MARKED: &str = "zz";

#[derive(Serialize)]
pub(crate) struct Language {
    pub(crate) code: String,
    pub(crate) name: String,
}

/// What the page needs for a language: its texts, English text to translation.
pub(crate) type Texts = BTreeMap<String, String>;

/// The languages a person can pick (not `zz`).
pub(crate) fn languages() -> Vec<Language> {
    LANGUAGES
        .iter()
        .filter_map(|(code, text)| {
            let file: serde_json::Value = serde_json::from_str(text).ok()?;
            let name = file["name"].as_str().unwrap_or(code).to_string();
            Some(Language {
                code: code.to_string(),
                name,
            })
        })
        .collect()
}

/// The text a key shows: `Open##verb` shows `Open`.
fn shown(key: &str) -> &str {
    key.split("##").next().unwrap_or(key)
}

/// A text in `zz`: `⟦text⟧`, and each form of a plural (`{n} photo|{n} photos`)
/// on its own, so the one `plural` picks is marked too.
fn marked(key: &str) -> String {
    let text = shown(key);
    if !text.starts_with("{n} ") {
        return format!("⟦{text}⟧");
    }
    text.split('|')
        .map(|form| format!("⟦{form}⟧"))
        .collect::<Vec<_>>()
        .join("|")
}

/// The texts of a language; `zz` wraps every text of the table in `⟦ ⟧`.
pub(crate) fn texts(code: &str) -> Result<Texts, String> {
    if code == MARKED {
        let keys: BTreeMap<String, serde_json::Value> =
            serde_json::from_str(KEYS).map_err(|e| format!("keys.json: {e}"))?;
        let built_in: Vec<String> =
            serde_json::from_str(BUILT_IN).map_err(|e| format!("built-in.json: {e}"))?;
        return Ok(keys
            .into_keys()
            .chain(built_in)
            .map(|k| {
                let text = marked(&k);
                (k, text)
            })
            .collect());
    }
    let (_, text) = LANGUAGES
        .iter()
        .find(|(c, _)| *c == code)
        .ok_or_else(|| format!("no language “{code}”"))?;
    let file: serde_json::Value =
        serde_json::from_str(text).map_err(|e| format!("language {code}: {e}"))?;
    serde_json::from_value(file["texts"].clone()).map_err(|e| format!("language {code}: {e}"))
}

/// The words of Rust's tables, which the UI shows through `t()`: each panel's
/// and section's label; each setting's label, help, "?" card and choices (the
/// registry and amb-protocol's `descriptions.json`); the mask fields' labels;
/// the built-in size presets' groups and names (`data/size-presets.json`).
pub(crate) fn built_in_texts() -> BTreeSet<String> {
    fn control(c: &crate::schema::Control, out: &mut BTreeSet<String>) {
        out.insert(c.label.clone());
        out.insert(c.description.clone());
        if let Some(coach) = &c.coach {
            out.extend(
                [Some(&coach.looks), coach.more.as_ref(), coach.less.as_ref()]
                    .into_iter()
                    .flatten()
                    .cloned(),
            );
        }
        out.extend(c.options.iter().map(|(_, l)| l.clone()));
        if let Some(r) = &c.rendered {
            control(r, out);
        }
    }
    let mut out = BTreeSet::new();
    for p in crate::schema::panels() {
        out.insert(p.label.to_string());
        for s in &p.sections {
            out.insert(s.label.clone());
            for c in &s.controls {
                control(c, &mut out);
            }
        }
    }
    let catalog = amb_protocol::catalog::Catalog::builtin();
    for g in catalog.groups() {
        out.extend([g.label.clone(), g.description.clone()]);
    }
    for tag in catalog.tags() {
        if let Some(text) = catalog.text(&tag.name) {
            out.extend([text.label.clone(), text.description.clone()]);
            if let Some(coach) = &text.coach {
                out.extend(
                    [Some(&coach.looks), coach.more.as_ref(), coach.less.as_ref()]
                        .into_iter()
                        .flatten()
                        .cloned(),
                );
            }
        }
    }
    out.extend(
        amb_protocol::masks::FIELD_RANGES
            .iter()
            .map(|f| f.label.to_string()),
    );
    let sizes: serde_json::Value =
        serde_json::from_str(include_str!("../data/size-presets.json")).unwrap_or_default();
    for g in sizes["groups"].as_array().into_iter().flatten() {
        out.extend(g["group"].as_str().map(String::from));
        let presets = g["presets"].as_array().into_iter().flatten();
        out.extend(presets.filter_map(|p| p["name"].as_str().map(String::from)));
    }
    out.retain(|t| t.chars().any(char::is_alphabetic));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn marked_language_wraps_every_key_and_drops_the_hint() {
        let t = texts("zz").unwrap();
        assert!(!t.is_empty(), "the table is empty: run tools/lang-table.py");
        for (k, v) in &t {
            let text = k.split("##").next().unwrap();
            if !text.starts_with("{n} ") {
                assert_eq!(v, &format!("⟦{text}⟧"));
            }
        }
        assert_eq!(t["{n} photo|{n} photos"], "⟦{n} photo⟧|⟦{n} photos⟧");
    }

    #[test]
    fn built_in_table_is_current() {
        let want = serde_json::to_string_pretty(&built_in_texts()).unwrap() + "\n";
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/data/lang/built-in.json");
        if std::env::var_os("AMB_UPDATE_DOCS").is_some() {
            std::fs::write(path, &want).unwrap();
        }
        assert!(
            BUILT_IN == want,
            "data/lang/built-in.json is stale: run `AMB_UPDATE_DOCS=1 cargo test -p amb-gui lang`"
        );
    }

    #[test]
    fn every_built_in_language_loads_and_has_a_name() {
        for (code, _) in LANGUAGES {
            assert!(texts(code).is_ok(), "{code}");
        }
        assert_eq!(languages().len(), LANGUAGES.len());
        assert!(texts("xx").is_err());
    }
}

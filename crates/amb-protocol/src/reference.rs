//! The settings reference (`docs/ai/settings-reference.md`), generated from the
//! tag registry and `data/descriptions.json` so it cannot drift from the code.

use std::fmt::Write as _;

use amb_presets::registry::{Status, TagInfo};
use amb_presets::xmp_writer::format_number;
use serde_json::json;

use crate::catalog::Catalog;

/// Command that regenerates the committed Markdown file.
pub const REGENERATE: &str =
    "cargo run -p amb-cli -- settings reference > docs/ai/settings-reference.md";

fn status_text(s: Status) -> &'static str {
    match s {
        Status::Planned => "planned",
        Status::Approx => "rendered (approx.)",
        Status::Exact => "rendered (exact)",
        Status::ImageSpecific => "image-specific",
        Status::Metadata => "metadata",
        Status::IgnoredInPresets => "ignored in presets",
        Status::Unsupported => "unsupported",
    }
}

fn range_text(t: &TagInfo) -> String {
    match (t.kind.as_str(), t.min, t.max) {
        (_, Some(lo), Some(hi)) => format!(
            "{} to {}",
            format_number(lo, false),
            format_number(hi, false)
        ),
        ("curve", _, _) => "points 0-255".into(),
        ("bool", _, _) => "true / false".into(),
        ("number", _, _) => "any number".into(),
        _ => String::new(),
    }
}

fn default_text(t: &TagInfo) -> String {
    match &t.default {
        None | Some(serde_json::Value::Null) => String::new(),
        Some(serde_json::Value::Number(n)) => format_number(n.as_f64().unwrap_or(0.0), false),
        Some(serde_json::Value::Bool(b)) => b.to_string(),
        Some(serde_json::Value::String(s)) => s.clone(),
        Some(other) => other.to_string(),
    }
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

/// The Markdown reference. Deterministic; ends with a newline.
pub fn markdown() -> String {
    let c = Catalog::builtin();
    let mut out = String::new();
    let _ = writeln!(out, "# Ambrotype settings reference");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "<!-- GENERATED by `amb settings reference` from crates/amb-presets/data/tags.json and crates/amb-protocol/data/descriptions.json. Do not edit by hand; regenerate with: {REGENERATE} -->"
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "Every Camera Raw (`crs:`) setting Ambrotype knows, grouped as in the tag registry. Use the **Tag** name with `amb edit` commands (`set_param`, `adjust_param`, `reset_param`) and the **group** name with `reset_group` and `apply_preset` filters. See [README.md](README.md) for how to drive Ambrotype."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "How to read the tables:");
    let _ = writeln!(
        out,
        "- **Range / Default**: best-known values from the registry. Most are not yet verified against Lightroom. Numbers outside the range are clamped, and the clamping is reported. An empty default means the value depends on the image (e.g. As Shot white balance) or the tag has no single default."
    );
    let _ = writeln!(
        out,
        "- A setting that is absent from a sidecar means \"untouched\": its default applies. `reset_param` removes a setting."
    );
    let _ = writeln!(
        out,
        "- **Status** is Ambrotype's rendering support: *rendered (approx.)* = the engine renders it with a model not yet fitted to Lightroom; *planned* = stored and round-tripped, not rendered yet; *image-specific* = depends on one photo (crop, auto settings), presets should rarely carry it; *metadata* = describes the file, not the look; *unsupported* = recognised AI/cloud feature, kept but never rendered."
    );
    let _ = writeln!(
        out,
        "- Descriptions follow Adobe's help (digested in `docs/adobe-docs/`). Where Adobe does not document something, the description says so."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "## Groups");
    let _ = writeln!(out);
    let _ = writeln!(out, "| Group | Name | Tags | About |");
    let _ = writeln!(out, "|---|---|---|---|");
    for g in c.groups() {
        let _ = writeln!(
            out,
            "| [{}](#{}) | `{}` | {} | {} |",
            cell(&g.label),
            g.name.replace('_', "-"),
            g.name,
            g.tags.len(),
            cell(&g.description)
        );
    }
    for g in c.groups() {
        let _ = writeln!(out);
        let _ = writeln!(out, "<a id=\"{}\"></a>", g.name.replace('_', "-"));
        let _ = writeln!(out);
        let _ = writeln!(out, "## {} (`{}`)", g.label, g.name);
        let _ = writeln!(out);
        if !g.description.is_empty() {
            let _ = writeln!(out, "{}", g.description);
            let _ = writeln!(out);
        }
        let _ = writeln!(
            out,
            "| Tag | Control | Kind | Range | Default | Status | Description |"
        );
        let _ = writeln!(out, "|---|---|---|---|---|---|---|");
        for name in &g.tags {
            let Some(t) = c.lookup(name) else { continue };
            let text = c.text(name);
            let label = text.map_or(String::new(), |t| t.label.clone());
            let mut desc = text.map_or(String::new(), |t| t.description.clone());
            if let Some(units) = text.and_then(|t| t.units.as_deref()) {
                desc = format!("*Units: {units}.* {desc}");
            }
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} | {} | {} |",
                t.name,
                cell(&label),
                t.kind,
                range_text(&t),
                cell(&default_text(&t)),
                status_text(t.status),
                cell(&desc)
            );
        }
    }
    out
}

/// The same information as JSON (for `amb settings reference --json`).
pub fn json() -> serde_json::Value {
    let c = Catalog::builtin();
    let groups: Vec<serde_json::Value> = c
        .groups()
        .iter()
        .map(|g| {
            let tags: Vec<serde_json::Value> = g
                .tags
                .iter()
                .filter_map(|n| c.lookup(n))
                .map(|t| {
                    let text = c.text(&t.name);
                    json!({
                        "name": t.name,
                        "label": text.map(|x| x.label.clone()),
                        "kind": t.kind,
                        "min": t.min,
                        "max": t.max,
                        "default": t.default,
                        "status": t.status,
                        "units": text.and_then(|x| x.units.clone()),
                        "description": text.map(|x| x.description.clone()),
                    })
                })
                .collect();
            json!({
                "name": g.name, "label": g.label, "description": g.description, "tags": tags,
            })
        })
        .collect();
    json!({
        "generated_from": ["crates/amb-presets/data/tags.json", "crates/amb-protocol/data/descriptions.json"],
        "groups": groups,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const COMMITTED: &str = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../docs/ai/settings-reference.md"
    );

    #[test]
    fn committed_reference_is_up_to_date() {
        let fresh = markdown();
        if std::env::var_os("AMB_UPDATE_DOCS").is_some() {
            std::fs::write(COMMITTED, &fresh).unwrap();
        }
        let committed = std::fs::read_to_string(COMMITTED).unwrap_or_default();
        assert!(
            committed == fresh,
            "docs/ai/settings-reference.md is stale (the tag registry or descriptions changed).\n\
             Regenerate it with:\n    {REGENERATE}\n\
             (or run this test with AMB_UPDATE_DOCS=1)"
        );
    }

    #[test]
    fn reference_mentions_every_tag() {
        let md = markdown();
        for t in Catalog::builtin().tags() {
            assert!(md.contains(&format!("| `{}` |", t.name)), "{}", t.name);
        }
        let j = json();
        let n: usize = j["groups"]
            .as_array()
            .unwrap()
            .iter()
            .map(|g| g["tags"].as_array().unwrap().len())
            .sum();
        assert_eq!(n, Catalog::builtin().tags().len());
    }
}
